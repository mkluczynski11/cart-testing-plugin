// Compiler: scenario -> Playwright test file. A pure function: the same scenario yields the same bytes.
import type { Scenario, ScenarioPick } from './scenario';
import { sha256 } from './scenario';

export const GENERATED_MARK = '// GENERATED by qa-harness compile. Change the scenario, not this file.';
const BODY_HASH = /^\/\/ body-sha256: ([0-9a-f]{64})$/m;
const SCENARIO_HASH = /^\/\/ scenario: (\S+) · sha256:([0-9a-f]{64})$/m;

function q(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, '\\n')}'`;
}

const varName = (alias: string) => alias.toLowerCase();

/** The largest state of a product in cart_after over all steps. */
export function needQty(s: Scenario, alias: string): number {
  return Math.max(1, ...s.steps.map((st) => st.cartAfter[alias] ?? 0));
}

export function reservedNames(s: Scenario): string[] {
  return s.aliases.flatMap((a) => {
    const p = s.products[a];
    return p.pick === 'by-name' ? [p.name] : [];
  });
}

function pickLiteral(s: Scenario, alias: string, pick: ScenarioPick): string {
  const need = needQty(s, alias);
  const needPart = need > 1 ? `, needQty: ${need}` : '';
  switch (pick.pick) {
    case 'first-available': return `{ pick: 'first-available'${needPart} }`;
    case 'next-available': return `{ pick: 'next-available', distinctFrom: [${pick.distinctFrom.map(varName).join(', ')}]${needPart} }`;
    case 'by-name': return `{ pick: 'by-name', name: ${q(pick.name)} }`;
  }
}

export function compileBody(s: Scenario): string {
  const out: string[] = [];
  out.push(`import { test } from '../support/core/fixtures';`);
  out.push('');
  out.push(`test.use({ scenario: ${q(s.id)}, reserved: [${reservedNames(s).map(q).join(', ')}] });`);
  out.push('');
  out.push(`test(${q(s.title)}, async ({ shopper }) => {`);
  const checkpoints = new Set(s.checkpoints);
  const declared = new Set<string>();
  for (const step of s.steps) {
    const v = varName(step.product);
    if (step.do === 'add') {
      if (!declared.has(step.product)) {
        declared.add(step.product);
        out.push(`  const ${v} = await shopper.add(${pickLiteral(s, step.product, s.products[step.product])}, ${step.qty});`);
      } else {
        out.push(`  await shopper.add(${v}, ${step.qty});`);
      }
    } else if (step.do === 'setQty') {
      out.push(`  await shopper.setQuantity(${v}, ${step.qty});`);
    } else {
      out.push(`  await shopper.remove(${v});`);
    }
    if (checkpoints.has(step.id)) out.push(`  await shopper.checkTotal(${q(step.id)});`);
  }
  out.push('});');
  return out.join('\n') + '\n';
}

export function compileScenario(s: Scenario, scenarioHash: string): string {
  const body = compileBody(s);
  const header = [
    GENERATED_MARK,
    `// scenario: ${s.id} · sha256:${scenarioHash}`,
    `// request: ${s.request.replace(/\s+/g, ' ').trim()}`,
    `// body-sha256: ${sha256(body)}`,
  ];
  return header.join('\n') + '\n' + body;
}

export type TestFileState = {
  generated: boolean; // has the header
  untouched: boolean; // body hash matches the recorded one
  scenarioId?: string;
  scenarioHash?: string;
};

/** Inspect an existing test file: was it compiled, and is its body untouched since then? */
export function inspectTestFile(text: string): TestFileState {
  const bodyMatch = BODY_HASH.exec(text);
  const scenMatch = SCENARIO_HASH.exec(text);
  if (!text.startsWith(GENERATED_MARK) || !bodyMatch) return { generated: false, untouched: false };
  const body = text.slice(bodyMatch.index + bodyMatch[0].length + 1);
  return {
    generated: true,
    untouched: sha256(body) === bodyMatch[1],
    scenarioId: scenMatch?.[1],
    scenarioHash: scenMatch?.[2],
  };
}
