// The compiler: scenario -> tests/<slug>.spec.ts. A pure function of the scenario: same scenario, same bytes.
// Implements design 8.4 (file shape, header, reserved names, needQty) and the compile contract of 6.1.
import { sha256, type Scenario, type ScenarioPick } from './scenario';

export const GENERATED_MARK = '// GENERATED by qa-harness compile. Change the scenario, not this file.';
const BODY_HASH = /^\/\/ body-sha256: ([0-9a-f]{64})$/m;
const SCENARIO_HASH = /^\/\/ scenario: (\S+) · sha256:([0-9a-f]{64})$/m;

function q(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, '\\n')}'`;
}

const varName = (alias: string) => alias.toLowerCase();

/** The largest state of a product in cart_after, not the largest step argument (8.3). */
export function needQty(s: Scenario, alias: string): number {
  return Math.max(1, ...s.steps.map((st) => st.cartAfter[alias] ?? 0));
}

/** Names the scenario gives to products: an unnamed pick never selects them. */
export function reservedNames(s: Scenario): string[] {
  return s.aliases.flatMap((a) => {
    const p = s.products[a];
    return p.pick === 'by-name' ? [p.name] : [];
  });
}

function whereLiteral(where: Record<string, string[]>): string {
  return `{ ${Object.entries(where).map(([k, v]) => `${/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : q(k)}: [${v.map(q).join(', ')}]`).join(', ')} }`;
}

function pickLiteral(s: Scenario, alias: string, pick: ScenarioPick): string {
  if (pick.pick === 'by-name') return `{ pick: 'by-name', name: ${q(pick.name)} }`;
  const need = needQty(s, alias);
  const filters = [need > 1 ? `needQty: ${need}` : '', pick.where ? `where: ${whereLiteral(pick.where)}` : ''].filter(Boolean);
  const filterPart = filters.length ? `, filters: { ${filters.join(', ')} }` : '';
  if (pick.pick === 'first-available') return `{ pick: 'first-available'${filterPart} }`;
  return `{ pick: 'next-available', distinctFrom: [${pick.distinctFrom.map(varName).join(', ')}]${filterPart} }`;
}

export function compileBody(s: Scenario): string {
  const reserved = reservedNames(s);
  const use = [`preconditions: [${s.preconditions.map(q).join(', ')}]`, `priceSource: ${q(s.priceSource)}`];
  if (reserved.length) use.push(`reserved: [${reserved.map(q).join(', ')}]`);
  const out = [`import { test } from '../support/core/fixtures';`, '', `test.use({ ${use.join(', ')} });`, '', `test(${q(s.title)}, async ({ shopper }) => {`];
  const checkpoints = new Set(s.checkpoints);
  const declared = new Set<string>();
  s.steps.forEach((step, i) => {
    const v = varName(step.product);
    if (step.do === 'add' && !declared.has(step.product)) {
      declared.add(step.product);
      out.push(`  const ${v} = await shopper.add(${pickLiteral(s, step.product, s.products[step.product])}, ${step.qty});`);
    } else if (step.do === 'add') out.push(`  await shopper.add(${v}, ${step.qty});`);
    else if (step.do === 'setQty') out.push(`  await shopper.setQuantity(${v}, ${step.qty});`);
    else out.push(`  await shopper.remove(${v});`);
    if (checkpoints.has(step.id)) {
      out.push(`  await shopper.checkTotal(${q(step.id)});`);
      if (i < s.steps.length - 1) out.push('');
    }
  });
  out.push('});');
  return out.join('\n') + '\n';
}

export function compileScenario(s: Scenario, scenarioSha256: string): string {
  const body = compileBody(s);
  return [
    GENERATED_MARK,
    `// scenario: ${s.id} · sha256:${scenarioSha256}`,
    `// request: ${s.request.replace(/\s+/g, ' ').trim()}`,
    `// body-sha256: ${sha256(body)}`,
  ].join('\n') + '\n' + body;
}

export type TestFileState = { generated: boolean; untouched: boolean; scenarioId?: string; scenarioSha256?: string };

/** Was the file compiled, and is its body untouched since then? (R14) */
export function inspectTestFile(text: string): TestFileState {
  const bodyMatch = BODY_HASH.exec(text);
  const scenMatch = SCENARIO_HASH.exec(text);
  if (!text.startsWith(GENERATED_MARK) || !bodyMatch) return { generated: false, untouched: false };
  const body = text.slice(bodyMatch.index + bodyMatch[0].length + 1);
  return { generated: true, untouched: sha256(body) === bodyMatch[1], scenarioId: scenMatch?.[1], scenarioSha256: scenMatch?.[2] };
}
