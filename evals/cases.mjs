const REFERENCE = 'Add two different products to the cart. Change the quantity of one, then remove the other. Check that the cart shows the correct total after each change.';
const SLUG = 'cart-total-add-change-remove';

/** The reference scenario of design 8.1 for the starter app, with optional changes to steps and status. */
function referenceScenario({ status = 'draft', s3 = 'A', s3qty = 3, s4 = 'B' } = {}) {
  const after3 = s3 === 'A' ? `{ A: ${s3qty}, B: 1 }` : `{ A: 1, B: ${s3qty} }`;
  const after4 = s4 === 'B' ? (s3 === 'A' ? `{ A: ${s3qty} }` : '{ A: 1 }') : (s3 === 'A' ? '{ B: 1 }' : `{ B: ${s3qty} }`);
  return `---
id: ${SLUG}
title: Cart total stays correct after add, quantity change and remove
app: toolshop
status: ${status}
request: "${REFERENCE}"
products:
  A: { pick: first-available }
  B: { pick: next-available, distinct_from: [A] }
steps:
  - { id: S1, do: add,    product: A, qty: 1, cart_after: { A: 1 } }
  - { id: S2, do: add,    product: B, qty: 1, cart_after: { A: 1, B: 1 } }
  - { id: S3, do: setQty, product: ${s3}, qty: ${s3qty}, cart_after: ${after3} }
  - { id: S4, do: remove, product: ${s4},         cart_after: ${after4} }
check: each-step
preconditions: [empty-cart, guest, no-geolocation]
price_source: ui
---

Two different products go into the cart; one changes quantity, then one is removed.
`;
}

/** Confirm and compile a scenario in a fixture, as the harness would after the tester's "ok". */
function confirmAndCompile(ctx, text, { intent = true, compile = true } = {}) {
  fs.writeFileSync(path.join(ctx.e2e, 'specs', `${SLUG}.md`), text);
  ctx.qa('example', SLUG);
  ctx.qa('example', SLUG, '--confirm');
  if (intent) {
    const hash = JSON.parse(fs.readFileSync(path.join(ctx.e2e, 'specs', `${SLUG}.example.json`), 'utf8')).confirmed.scenarioSha256;
    fs.writeFileSync(path.join(ctx.e2e, 'specs', `${SLUG}.intent.md`), `---\nscenario: ${SLUG}\nscenario_sha256: ${hash}\nverdict: INTENT_OK\n---\n\n# Intent review of ${SLUG}\n\nFixture of the eval: every clause covered.\n`);
  }
  if (compile) ctx.qa('compile', SLUG);
}

// ---- graders ----
const specs = (f) => (fs.existsSync(path.join(f.e2e, 'specs')) ? fs.readdirSync(path.join(f.e2e, 'specs')).filter((n) => n.endsWith('.md') && !n.endsWith('.intent.md')) : []);
const tests = (f) => (fs.existsSync(path.join(f.e2e, 'tests')) ? fs.readdirSync(path.join(f.e2e, 'tests')).filter((n) => n.endsWith('.spec.ts')) : []);
const frontMatter = (file) => parseYaml(/^---\n([\s\S]*?)\n---/.exec(fs.readFileSync(file, 'utf8'))[1]);
const onlyScenario = (f) => {
  const s = specs(f);
  if (s.length !== 1) throw new Error(`expected one scenario, found ${s.length}: ${s.join(', ')}`);
  return { slug: s[0].replace(/\.md$/, ''), data: frontMatter(path.join(f.e2e, 'specs', s[0])) };
};
const harnessCalls = (f, re) => f.calls.filter((c) => c.name === 'Bash' && re.test(String(c.input?.command ?? '')));
/** The confirmation shows the first line of `qa-harness defects check`, verbatim (design 11.1, order E stage 1). */
const defectsLine = (re) => (f) => {
  const printed = harnessCalls(f, /qa-harness defects check /).flatMap((c) => c.result.split('\n')).filter((l) => /^The test will be checked against /.test(l));
  if (!printed.length) return 'no defects check printed the line';
  const hit = printed.find((l) => (f.texts ?? []).join('\n').includes(l));
  if (!hit) return `not shown: ${printed[0]}`;
  return re.test(hit) || hit;
};
const verdictOf = (call) => [...(call?.result ?? '').matchAll(/VERDICT: ([A-Z_]+)/g)].pop()?.[1];
const skillUsed = (f, name) => f.calls.some((c) => c.name === 'Skill' && new RegExp(`^(qa:)?${name}$`).test(String(c.input?.skill ?? '')));
const gitChanged = (f, prefix) => spawnSync('git', ['status', '--porcelain', '--untracked-files=all', '--', prefix], { cwd: f.repo, encoding: 'utf8' }).stdout.trim();
const endsWithQuestion = (text) => /\?\s*[*_`)"]*\s*$/.test(text.trim()) || /\?[^\n]*$/.test(text.trim().split('\n').filter(Boolean).pop() ?? '');
const subagent = (f, type) => Number(f.json.subagent_stats?.by_type?.[type] ?? 0);

const compiledWithCheckpoints = (n) => (f) => {
  const { slug } = onlyScenario(f);
  const file = path.join(f.e2e, 'tests', `${slug}.spec.ts`);
  if (!fs.existsSync(file)) return `tests/${slug}.spec.ts missing`;
  const text = fs.readFileSync(file, 'utf8');
  if (!text.startsWith('// GENERATED by qa-harness compile.')) return 'the test has no compile header';
  const count = (text.match(/shopper\.checkTotal\(/g) ?? []).length;
  return count === n || `${count} checkpoints`;
};
/** G0-G2 green: the newest run directory of the scenario records a green dry verdict (written by the harness). */
const dryGreen = (f) => {
  const { slug } = onlyScenario(f);
  const runs = path.join(f.e2e, 'reports', slug, 'runs');
  const ids = fs.existsSync(runs) ? fs.readdirSync(runs).filter((d) => fs.existsSync(path.join(runs, d, 'verification.json'))).sort() : [];
  if (!ids.length) return 'no run directory with verification.json';
  const v = JSON.parse(fs.readFileSync(path.join(runs, ids[ids.length - 1], 'verification.json'), 'utf8'));
  return (v.gates?.dry === 'PASS' && v.verdict === 'PASS') || `dry ${v.gates?.dry}, verdict ${v.verdict}`;
};
const compiledByHarness = (f) => harnessCalls(f, /qa-harness compile /).some((c) => verdictOf(c) === 'PASS') || 'no qa-harness compile ended PASS';
const noTestWritten = (f) => !f.calls.some((c) => ['Write', 'Edit'].includes(c.name) && /\/tests\//.test(String(c.input?.file_path ?? ''))) || 'the model wrote under tests/';

